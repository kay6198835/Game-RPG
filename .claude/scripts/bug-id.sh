#!/usr/bin/env bash
# bug-id.sh — the single bug-ID authority helper. Read-only.
#
#   bug-id.sh next    Print the next free ID (max BUG-NNN in production/qa/bugs/ + 1, 3 digits).
#                     Only /weekly-wrapup may use this (see .claude/rules/bug-inbox.md).
#   bug-id.sh audit   Markdown report: IDs cited in living docs with no file, bug files with no
#                     **Status** line, bug-table rows left in CLAUDE.md, and whether
#                     production/qa/open-bugs.md is current.
#   bug-id.sh open    Print the open-bug index (every bug file whose status is not FIXED / CLOSED /
#                     ACCEPTED), generated from the bug files. Write it with:
#                       bash .claude/scripts/bug-id.sh open > production/qa/open-bugs.md
#                     CLAUDE.md links to that file and never copies bug rows (2026-11-19).
#
# Run from the repo root (or pass REPO=<path>).
set -u
REPO="${REPO:-.}"
BUGS="$REPO/production/qa/bugs"

max_id() {
  ls "$BUGS" 2>/dev/null | sed -n 's/^BUG-\([0-9][0-9]*\)\.md$/\1/p' | sed 's/^0*//' | sort -n | tail -1
}

status_of() { # $1 = bug file; prints the **Status** value (first 60 chars) or empty
  grep -m1 -E '^\*\*Status\*\*' "$1" 2>/dev/null | sed -E 's/^\*\*Status\*\*:? *//' | cut -c1-60
}

classify() { # status text -> the status keyword that appears FIRST (later text is usually history)
  printf '%s' "$1" | tr '[:lower:]' '[:upper:]' | awk '
    { best=""; bp=1e9
      n=split("ACCEPTED:ACCEPTED DEFER:ACCEPTED PARTIAL:PARTIAL CLOSED:CLOSED FIXED:FIXED REOPEN:OPEN OPEN:OPEN CONFIRMED:OPEN", kv, " ")
      for (i=1;i<=n;i++){ split(kv[i],p,":"); k=index($0,p[1]); if (k>0 && k<bp){bp=k; best=p[2]} }
      print (best=="" ? "?" : best) }'
}

field_of() { # $1 = bug file, $2 = field name; prints the field value on its header line
  grep -m1 -E "^\*\*$2\*\*" "$1" 2>/dev/null | sed -E "s/^\*\*$2\*\*:? *//"
}

cmd_open() {
  echo "# Open bugs"
  echo
  echo "> Generated by \`bash .claude/scripts/bug-id.sh open > production/qa/open-bugs.md\` from"
  echo "> \`production/qa/bugs/*.md\`. Do not edit by hand — the bug files are the source of truth."
  echo "> Lists every bug whose \`**Status**\` is not FIXED / CLOSED / ACCEPTED (PARTIAL counts as open)."
  echo
  echo "| ID | Sev | Status | Title |"
  echo "|---|---|---|---|"
  local f id st cls sev title
  for f in "$BUGS"/BUG-*.md; do
    id=$(basename "$f" .md)
    st=$(status_of "$f")
    cls=$(classify "$st")
    case "$cls" in FIXED|CLOSED|ACCEPTED) continue ;; esac
    sev=$(field_of "$f" Severity | grep -oE 'S[1-4]' | head -1)
    title=$(field_of "$f" Title | sed 's/|/\|/g' | cut -c1-140)
    printf '%s\t| [%s](bugs/%s.md) | %s | %s | %s |\n' "${sev:-S9}" "$id" "$id" "${sev:-?}" "$cls" "$title"
  done | sort -t "$(printf '\t')" -k1,1 -s | cut -f2-
}

cmd_next() {
  local m; m=$(max_id); m=${m:-0}
  printf 'BUG-%03d\n' $((m + 1))
}

cmd_audit() {
  local living
  living=$(ls "$REPO"/CLAUDE.md "$REPO"/.claude/rules/*.md "$REPO"/design/gdd/*.md \
              "$REPO"/docs/systems/*/README.md "$REPO"/docs/ui/ui-ux-flow.md \
              "$REPO"/docs/architecture/adr-*.md 2>/dev/null | grep -v 'cross-review')

  echo "## Bug-ID audit"
  echo
  echo "Next free ID: \`$(cmd_next)\` · bug files: $(ls "$BUGS"/BUG-*.md 2>/dev/null | wc -l | tr -d ' ')"
  echo
  echo "### 1. IDs cited in living docs with no bug file"
  echo
  echo "| ID | Cited in |"
  echo "|---|---|"
  local found=0
  for id in $(grep -ohE 'BUG-[0-9]{3}' $living 2>/dev/null | sort -u); do
    if [ ! -f "$BUGS/$id.md" ]; then
      echo "| $id | $(grep -lE "$id\b" $living | sed "s#^$REPO/##" | tr '\n' ' ') |"
      found=1
    fi
  done
  [ $found -eq 0 ] && echo "| — | none |"

  echo
  echo "### 2. Bug files with no \`**Status**\` line"
  echo
  found=0
  for f in "$BUGS"/BUG-*.md; do
    [ -z "$(status_of "$f")" ] && { echo "- $(basename "$f" .md)"; found=1; }
  done
  [ $found -eq 0 ] && echo "- none"

  echo
  echo "### 3. Bug rows copied into CLAUDE.md (must be none — link production/qa/open-bugs.md)"
  echo
  found=0
  if grep -nE '^\s*\| *\[?BUG-[0-9]{3}' "$REPO/CLAUDE.md" 2>/dev/null; then found=1; fi
  [ $found -eq 0 ] && echo "- none"

  echo
  echo "### 4. production/qa/open-bugs.md is current"
  echo
  if [ ! -f "$REPO/production/qa/open-bugs.md" ]; then
    echo "- MISSING — run \`bash .claude/scripts/bug-id.sh open > production/qa/open-bugs.md\`"
  elif cmd_open | tr -d '' | cmp -s - <(tr -d '' < "$REPO/production/qa/open-bugs.md"); then
    echo "- current"
  else
    echo "- STALE — regenerate with \`bash .claude/scripts/bug-id.sh open > production/qa/open-bugs.md\`"
  fi
}

case "${1:-}" in
  next) cmd_next ;;
  audit) cmd_audit ;;
  open) cmd_open ;;
  *) echo "usage: bug-id.sh next|audit|open" >&2; exit 2 ;;
esac
